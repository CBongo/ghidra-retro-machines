// "=== BANKDUMP END ===" markers (memory blocks with their overlay-ness, EOL
// comments containing "bank ->", bookmarks in the *BankingAnalyzer category, and
// instruction references into overlay spaces), then evaluates per-program
// criteria, printing one "CRITERION <id> PASS|FAIL <detail>" line each and
// "SUITE PASS" only when all criteria passed. Detects which test program it is
// running against by the program name.
//@category RetroMachines.Test

