// Verifies C64BankingAnalyzer and NesBankingAnalyzer behavior on the banktest*
// regression PRGs (C64, generated by mkbanktest.py) and the nesbanktest ROM (NES,
// generated by mknesbanktest.py; driven by run-banktest.sh).
