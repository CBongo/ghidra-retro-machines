public class VerifyBankTest extends GhidraScript {

	/** Run-wide verdict shared by the criteria families; lives as long as this script instance. */
	private final VerifyBase.Verdict verdict = new VerifyBase.Verdict();

	// The criteria families, rebuilt by registerChecks() on every run() once currentProgram is set.
	private VerifyDumpCriteria dumpCriteria;
	private VerifyCbmCriteria cbm;
	private VerifyDescriptorCriteria desc;
	private VerifyNesCriteria nes;

	/** One fixture's verification body; may throw like run() itself. */
	private interface Check {
		void run() throws Exception;
	}

	/**
	 * Fixture name (the imported file's name without its extension) -> how it is verified. Exact
	 * match only: an unregistered name hard-fails in run() instead of falling through to a default
	 * (bd memory fixture-dispatch-two-sided; bead grm-w9ev.2). Register a new fixture here AND in
	 * run-banktest.sh.
	 */
	private final Map<String, Check> checks = new LinkedHashMap<>();

	/** A focused check that bypasses dump() and the generic identity criteria. */
	private void focused(String fixture, Check check) {
		register(fixture, check);
	}

	/** A bank-style fixture: dump(), the generic identity criteria, then its own check. */
	private void dumped(String fixture, Check check) {
		register(fixture, () -> {
			dumpCriteria.dump();
			dumpCriteria.checkGameIdentity();
			dumpCriteria.checkAsyncEntryPoints();
			check.run();
		});
	}

	private void register(String fixture, Check check) {
		if (checks.put(fixture, check) != null) {
			throw new IllegalStateException("fixture registered twice: " + fixture);
		}
	}

	private void registerChecks() {
		// run() rebuilds the map each time, so a script instance reused across programs (e.g. one
		// headless JVM importing several fixtures, grm-w9ev.5) does not trip register()'s guard.
		checks.clear();
		dumpCriteria = new VerifyDumpCriteria(this, verdict);
		cbm = new VerifyCbmCriteria(this, verdict);
		desc = new VerifyDescriptorCriteria(this, verdict);
		nes = new VerifyNesCriteria(this, verdict);
		// Focused checks (no dump()): the emulation/PRG/copy/BASIC/SNES families.
		focused("emurecoverytest", cbm::checkEmuRecovery);
		focused("c000emutest", cbm::checkC000EmuRecovery);
		focused("prgplacementtest", cbm::checkPrgPlacement);
		focused("prgwraptest", cbm::checkPrgWrap);
		focused("prgnowraptest", cbm::checkPrgNoWrap);
		focused("prgwrap1test", cbm::checkPrgWrap1);
		focused("prgfulltest", cbm::checkPrgFull);
		focused("prgentrytest", cbm::checkPrgEntry);
		focused("prgstraddletest", cbm::checkPrgStraddle);
		focused("prgemptytest", cbm::checkPrgEmpty);
		focused("decryptloop", cbm::checkDecryptLoop);
		focused("rollingdecrypt", cbm::checkRollingDecrypt);
		focused("suspectdecrypt", cbm::checkSuspectDecrypt);
		focused("copyloop", cbm::checkCopyLoop);
		focused("copydata", cbm::checkCopyData);
		focused("copyoverlay", cbm::checkCopyOverlay);
		focused("copyfar", cbm::checkCopyFar);
		focused("copychain", cbm::checkCopyChain);
		// The copybanked* runs share checkCopyBanked / checkCopyBankedSrc, which key off the full
		// name for the single criterion that differs (the *rom variants); the src and inplace
		// pairs are REQUIRED to differ from plain copybanked (grm-9a0).
		focused("copybanked", cbm::checkCopyBanked);
		focused("copybankedrom", cbm::checkCopyBanked);
		focused("copybankedsrc", cbm::checkCopyBankedSrc);
		focused("copybankedsrcrom", cbm::checkCopyBankedSrc);
		focused("copybankedinplace", cbm::checkCopyBankedInPlace);
		focused("copybankedinplacerom", cbm::checkCopyBankedInPlace);
		// The NES copy fixture takes the focused COPYBLOCK dump (not the NES bank dump()). Its
		// block carries no IDENTITY line but it is still an NES import, so the identity criteria
		// apply -- criterion lines print after verifyCopy's "=== BANKDUMP END ===", so this moves
		// no golden.
		focused("nescopytest", () -> {
			cbm.checkNesCopyLoop();
			dumpCriteria.checkGameIdentity();
			dumpCriteria.checkAsyncEntryPoints();
		});
		// cp-renamed alias fixtures (run-banktest.sh copies another PRG to these names).
		focused("rfemanual", cbm::checkRfeManual);
		focused("copyhinttest", cbm::checkCopyHint);
		focused("copyhintnorom", cbm::checkCopyHintNoRom);
		focused("symtoggle", cbm::checkSymToggle);
		focused("romload", cbm::checkRomLoad);
		focused("pet4032test", cbm::checkPet4032);
		focused("snestest", cbm::checkSnes);
		focused("snestestcopier", cbm::checkSnes);
		focused("snestestinterleaved", cbm::checkSnesInterleaved);
		focused("c128nativebasic7test", cbm::checkC128NativeBasic7);
		focused("c64basic2tokentest", cbm::checkC64Basic2Dialect);
		focused("c64basicoverflowtest", cbm::checkC64BasicOverflowDialect);
		focused("petbasic4test", cbm::checkPetBasic4Dialect);
		focused("c128basic7test", cbm::checkC128Basic7Dialect);
		focused("petsciistringtest", cbm::checkPetsciiStringTest);
		// grm-s3wo: same string layout as nestbltest, in a LoROM cartridge; the byte-mapped
		// mirror of bank 00 sits at $80:8000 (grm-a6n0: it must stay unannotated).
		focused("snestbltest", () -> cbm.checkTblTest("snes", 0x800000L, "snestbltest.tbl"));
		// grm-a6n0: 16 KiB PRG, mirrored byte-mapped at $C000.
		focused("nestbltest16", () -> cbm.checkTblTest("nes16", 0x4000L, "nestbltest.tbl"));
		focused("nestbltest", () -> cbm.checkTblTest("nes", 0L, "nestbltest.tbl"));

		// dump()-based fixtures: C64 banking, descriptor and NES board suites.
		dumped("banktest", cbm::checkBanktest);
		dumped("banktest2", cbm::checkBanktest2);
		dumped("banktest3", cbm::checkBanktest3);
		dumped("banktest4", cbm::checkBanktest4);
		dumped("c64basictest", cbm::checkC64Basictest);
		dumped("descoverlaytest", () -> desc.checkDescOverlay(true));
		dumped("descoverlayctltest", () -> desc.checkDescOverlay(false));
		// The generic dump + identity criteria are the whole post-import story; the substance
		// (re-running DescriptorAnnotationAnalyzer one-shot) is the post-verify
		// AssertDescriptorReanalysis.java script's (bead grm-hb6.16).
		dumped("descannotationtest", () -> { });
		// Phase A of the export round trip (grm-hb6.17): the dump is the plain import; the
		// seeding and export are post-verify scripts.
		dumped("descexporttest", () -> { });
		dumped("descreimporttest", () -> {
			String path = currentProgram.getOptions(Program.PROGRAM_INFO)
					.getString(VerifyDescriptorCriteria.GAME_DESCRIPTOR_PROPERTY, null);
			String norm = path == null ? null : path.replace('\\', '/');
			dumpCriteria.criterion("REIMP1:exported-overlay-resolved",
				norm != null && norm.endsWith("/retro-machines/games/descexportedtest.yaml"),
				"Game Descriptor property = " + path);
		});
		dumped("descbankhinttest", desc::checkDescBankHint);
		dumped("descbankhintmmc3test", desc::checkDescBankHintMmc3);
		dumped("nesrelaytest", nes::checkNesRelayTest);
		dumped("neswrappertest", nes::checkNesWrapperTest);
		dumped("nesmmc1overridetest", nes::checkNesMmc1Override);
		dumped("nesmmc3overridetest", nes::checkNesMmc3Override);
		dumped("nesmmc3mirrortest", nes::checkNesMmc3Mirrortest);
		dumped("nesmmc3idtest", nes::checkNesMmc3Idtest);
		dumped("nesmmc1test", nes::checkNesMmc1test);
		dumped("nesmmc1varytest", nes::checkNesMmc1Vary);
		dumped("nesmmc1mismatchtest", nes::checkNesMmc1Mismatch);
		dumped("nesserialtest", nes::checkNesSerialtest);
		dumped("nesmmc3test2", nes::checkNesMmc3test2);
		dumped("nesmmc3modetest", nes::checkNesMmc3Modetest);
		dumped("nesmmc3splittest", nes::checkNesMmc3Splittest);
		dumped("nesmmc3test", nes::checkNesMmc3test);
		dumped("nesnromsubtest", nes::checkNesNromSubtest);
		dumped("nesmodetest", nes::checkNesModetest);
		dumped("nesmmc2test", nes::checkNesMmc2test);
		dumped("nesmmc5wraptest", nes::checkNesMmc5Wraptest);
		dumped("nesmmc5test", nes::checkNesMmc5test);
		dumped("nesbandaitest", nes::checkNesBandaitest);
		dumped("nesuxhelpertest", nes::checkNesUxHelpertest);
		dumped("nesskiptest", nes::checkNesSkiptest);
		dumped("nesmirrortest", nes::checkNesMirrortest);
		dumped("nesnmitest", nes::checkNesNmitest);
		dumped("nesforkbudgettest", nes::checkNesForkBudgettest);
		dumped("nesintrawintest", nes::checkNesIntrawintest);
		dumped("nesforkhometest", nes::checkNesForkHometest);
		dumped("nesforktest", nes::checkNesForktest);
		dumped("nesbanktest2", nes::checkNesBanktest2);
		dumped("nesbanktest", nes::checkNesBanktest);
	}

	@Override
	protected void run() throws Exception {
		// First output of the run: run-banktest.sh splits a multi-program (batched) log on this
		// line (bead grm-w9ev.5). Not a CRITERION/SUITE/BANKDUMP line, so it reaches no golden.
		println("=== FIXTURE " + currentProgram.getName() + " ===");
		registerChecks();

		// The program name is the imported file's name; fixtures are registered without extension.
		String name = currentProgram.getName();
		int dot = name.lastIndexOf('.');
		String fixture = dot > 0 ? name.substring(0, dot) : name;

		Check check = checks.get(fixture);
		if (check == null) {
			dumpCriteria.criterion("DISPATCH:unregistered-fixture", false,
				"no check registered for fixture '" + fixture + "' (program " + name
					+ "); add it to VerifyBankTest.registerChecks()");
			println("SUITE FAIL");
			return;
		}

		check.run();
		println(verdict.allPassed ? "SUITE PASS" : "SUITE FAIL");
	}
}
